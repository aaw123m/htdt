"""Repo-synthesized interoperability corpus fixtures (#892).

Every fixture byte string here is generated deterministically in-repo —
no third-party file is vendored, so the corpus is redistribution-safe by
construction. ``build_default_corpus_manifest`` seals the corpus into a
versioned :class:`InteropCorpusManifest` whose fixture pins
(``content_sha256`` + ``size_bytes``) make any drift a detectable
regression rather than silent acceptance.

``materialize_corpus`` writes the byte corpus under a directory the
harness reads; keeping bytes and manifest in sync is mechanical: the
manifest is built FROM the generated bytes.
"""

