def _sha(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def build_default_corpus_manifest(
    *, issued_on: str = _TS
) -> InteropCorpusManifest:
    """Seal the default in-repo corpus manifest."""
    return InteropCorpusManifest.create(
        corpus_id=INTEROP_CORPUS_ID,
        corpus_version=INTEROP_CORPUS_VERSION,
        issued_on=issued_on,
        fixtures=_entries(),
    )


def default_fixture_bytes() -> dict[str, bytes]:
    """Fresh deterministic bytes for every default fixture path."""
    return {path: gen() for path, gen in GENERATORS.items()}


def materialize_corpus(
    manifest: InteropCorpusManifest,
    target_dir: Path,
    *,
    payload_overrides: dict[str, bytes] | None = None,
) -> None:
    """Write corpus files under *target_dir* matching *manifest*.

    ``payload_overrides`` lets tests inject drifted bytes under a
    fixture's declared path; the harness then reports the pin mismatch
    as ``unexpected_failure`` (fixture drift is evidence, not a pass).
    """
    overrides = payload_overrides or {}
    bytes_map = default_fixture_bytes()
    for entry in manifest.fixtures:
        payload = overrides.get(entry.relative_path)
        if payload is None:
            payload = bytes_map.get(entry.relative_path)
        if payload is None:
            raise ValueError(
                f'no generated bytes for fixture {entry.relative_path}'
            )
        path = target_dir / entry.relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)


